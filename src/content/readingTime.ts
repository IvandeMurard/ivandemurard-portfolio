import type { JournalBlock } from "./journal";
import { APPLY_GUIDES } from "./journalApply";
import { recoLineMarkdown } from "./recoLine";
import { blueprintMarkdown } from "./serviceBlueprint";

/** First sentence of a text: what stays visible before "Read more". */
export const firstSentence = (t: string) => {
  const m = t.match(/^.*?[.!?](?=\s|$)/);
  return m ? m[0] : t;
};

/**
 * What a reader sees by default: the blocks counted so far, with folds, collapsed table text and folded questions left
 * out. This is the method behind the headline number; it does not change.
 */
const shownText = (b: JournalBlock): string[] => {
  switch (b.kind) {
    case "p": case "h2": case "h3": case "quote": case "code": return [b.text];
    case "list": return b.items;
    case "table": return [...b.head, ...b.rows.flatMap((r) => r.map((c, i) => (i === b.foldCol ? firstSentence(c) : c)))];
    case "defs": return b.items.map((i) => `${i.term} ${i.def}`);
    case "lines": return (b.visible ? b.items.filter((i) => b.visible!.includes(i.q)) : b.items).flatMap((i) => [i.q, i.a]);
    case "key": return [b.oneLine, b.concrete ?? ""];
    case "cards": return b.items.map((i) => `${i.title} ${i.body}`);
    case "recoLine": return [b.caption];
    case "peak": {
      // The boxes come after one answer: they are part of the peak a reader goes through, not a fold. One reveal line is read.
      const c = b.challenge;
      return [b.kicker, b.lead, c?.rule ?? "", c?.question ?? "", c ? [...c.reveal].sort((x, y) => y.length - x.length)[0] : "", ...b.boxes.flatMap((x) => [x.label, x.text, x.note ?? "", x.bubble ?? ""]), b.after ?? "", b.contract ?? ""];
    }
    default: return [];
  }
};

/**
 * Every prose text a reader can open or read on the page: all table cells in full, the figures (captions, labels and
 * data), the replay and the challenge, the disclosures and every FAQ answer. Left out: the copy-paste brief of "Apply this
 * to your project" and the Updates log, which are for a program or a record, not for reading.
 */
const fullText = (b: JournalBlock, extra: string[]): string[] => {
  switch (b.kind) {
    case "table": return [b.caption ?? "", ...b.head, ...b.rows.flat()];
    case "defs": return b.items.flatMap((i) => [i.term, i.def, i.note ?? ""]);
    case "lines": return b.items.flatMap((i) => [i.q, i.a]);
    case "recoLine": return [b.caption, recoLineMarkdown(b.layer), b.link?.text ?? ""];
    case "fold": return [b.summary, ...b.blocks.flatMap((x) => fullText(x, extra))];
    case "anchors": return [b.label ?? "", ...b.items.flatMap((i) => [i.project, i.what, i.who, i.feedback])];
    case "timeline": return [b.label ?? "", ...b.steps.flatMap((s) => [s.value, s.label, s.note ?? ""])];
    case "matrix": return [b.label ?? "", ...b.columns, ...b.rows.flatMap((r) => [r.arm, r.when, ...r.cells.flatMap((c) => [c.state, c.instance, c.cost ?? ""])])];
    case "pyramid": return b.layers.flatMap((l) => [l.level, l.name, l.note ?? "", l.detail ?? "", l.product ?? "", l.signal ?? ""]);
    case "deployed": return b.items.flatMap((i) => [i.project, i.text]);
    case "stepper":
      return [
        b.label ?? "", b.question, b.rule, b.answer, b.note ?? "", b.reveal.pass, b.reveal.fail,
        ...b.steps.flatMap((s) => [s.tab, s.verdict, ...s.checks.flatMap((c) => [c.grader, c.result]), s.reading, s.answer ?? ""]),
      ];
    case "vocab": return [b.label ?? "", ...b.items.map((i) => i.label)];
    case "arms": return [b.label ?? "", "Arm A: offline before the merge. Arm B: runtime in production. Arm C: outcome after the fact.", b.link?.text ?? ""];
    case "callout": return [b.title, b.text, b.link.text];
    case "askRose": return [b.label ?? "", b.note ?? "", ...b.prompts];
    case "mcp": return [b.label ?? "", b.note ?? ""];
    case "trap": return [b.question, ...b.choices, ...b.reveal];
    case "blueprint": return [blueprintMarkdown()];
    case "apply": {
      const g = APPLY_GUIDES[b.slug];
      return g ? [g.decision, ...g.inputs, g.artifact, g.verify] : [];
    }
    case "diagnostic": return extra;
    // The console is generated by the page, not authored prose.
    case "console": return [];
    default: return shownText(b);
  }
};

const words = (texts: string[]): number => texts.join(" ").split(/\s+/).filter(Boolean).length;

/** Words with every fold open (see fullText). `extra`: the text of the note's self-diagnostic, when it sits in the body. */
export const fullWords = (body: JournalBlock[], extra: string[] = []): number => words(body.flatMap((b) => fullText(b, extra)));

/** Words of what a reader sees by default. */
export const visibleWords = (body: JournalBlock[]): number => words(body.flatMap(shownText));

/** Minutes of what a reader sees by default: folded passages, collapsed table text and folded questions are excluded. */
export const visibleMinutes = (body: JournalBlock[], wpm = 230) => Math.max(1, Math.round(visibleWords(body) / wpm));

/** Minutes with every fold open. */
export const fullMinutes = (body: JournalBlock[], wpm = 230, extra: string[] = []) => Math.max(1, Math.round(fullWords(body, extra) / wpm));

/** The full count is worth saying when it is at least this many minutes longer than the default one. */
export const FULL_GAP_MINUTES = 5;

/**
 * The reading-time label, computed: "18 min", or "18 min · 36 with every detail open" when the full count is at least
 * five minutes longer. Never typed.
 */
export const readingLabel = (visible: number, full?: number): string =>
  full !== undefined && full - visible >= FULL_GAP_MINUTES ? `${visible} min · ${full} with every detail open` : `${visible} min`;
