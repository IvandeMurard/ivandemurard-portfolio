// Prebuild: writes src/content/sectionIndex.generated.ts, the headings of every Field Note, so that a link from
// Rose to "/journal/<slug>#<heading>" can be labelled "§ <heading>" without loading the note.
// Only the path, the title and, for each heading, its id and text. No body text.
// Run with bun (tsconfig path aliases). Rewrites the file only when its content changed.

import { resolve } from "path";
import { JOURNAL_ENTRIES } from "@/content/journal";
import { journalHeadingIds } from "@/lib/journalHeadingIds";
import { writeIfChanged } from "./content-date";

type Section = { id: string; heading: string };
type Entry = { path: string; title: string; sections: Section[] };

const entries: Entry[] = JOURNAL_ENTRIES.map((entry) => {
  const ids = journalHeadingIds(entry.body);
  const sections: Section[] = [];
  entry.body.forEach((block, i) => {
    const id = ids[i];
    if (!id || (block.kind !== "h2" && block.kind !== "h3")) return;
    sections.push({ id, heading: block.text });
    // An alias is an older id for the same heading: links that used it keep working and keep the same label.
    for (const alias of block.aliases ?? []) sections.push({ id: alias, heading: block.text });
  });
  return { path: `/journal/${entry.slug}`, title: entry.title, sections };
});

const out = [
  "// Generated by scripts/generate-section-index.ts from src/content/journal.ts. Do not edit.",
  "// Path, title and headings of each Field Note. No body text.",
  "",
  "export type SectionIndexEntry = { path: string; title: string; sections: Array<{ id: string; heading: string }> };",
  "",
  "export const SECTION_INDEX: SectionIndexEntry[] = [",
  ...entries.flatMap((e) => [
    "  {",
    `    path: ${JSON.stringify(e.path)},`,
    `    title: ${JSON.stringify(e.title)},`,
    "    sections: [",
    ...e.sections.map((s) => `      { id: ${JSON.stringify(s.id)}, heading: ${JSON.stringify(s.heading)} },`),
    "    ],",
    "  },",
  ]),
  "];",
  "",
].join("\n");

const changed = writeIfChanged(resolve("src/content/sectionIndex.generated.ts"), out);
console.log(`[section-index] ${changed ? "wrote" : "unchanged:"} src/content/sectionIndex.generated.ts, ${Buffer.byteLength(out)} bytes, ${entries.length} entries`);
