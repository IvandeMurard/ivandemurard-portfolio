import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { ROSE_PURPOSE, ROSE_HISTORY, ROSE_CAPABILITIES, ROSE_LIMITS } from "../src/content/roseHistory";
import { ROSE_SELF_PERSONA } from "../src/content/rosePersona";

const classes = new Set(["implemented", "lab", "interpretation", "synthetic", "hypothesis"]);
const ids = new Set<string>();
for (const entry of ROSE_HISTORY) {
  if (ids.has(entry.id) || !classes.has(entry.claim)) throw new Error(`Invalid history entry: ${entry.id}`);
  ids.add(entry.id);
  if (entry.date && (!/^\d{4}-\d{2}-\d{2}$/.test(entry.date) || new Date(entry.date).toISOString().slice(0, 10) !== entry.date)) throw new Error(`Invalid date: ${entry.id}`);
  for (const hash of entry.provenance.commits) if (!/^[a-f0-9]{7,40}$/.test(hash)) throw new Error(`Invalid commit: ${entry.id}`);
  for (const path of [...entry.provenance.files, ...entry.provenance.plans]) if (!existsSync(path)) throw new Error(`Missing provenance: ${path}`);
}
const source = JSON.stringify({ ROSE_PURPOSE, ROSE_HISTORY, ROSE_CAPABILITIES, ROSE_LIMITS, ROSE_SELF_PERSONA });
const hash = createHash("sha256").update(source).digest("hex");
const reference = [
  "Rose historical reference, v1. Repository evidence, not verified deployment parity. No measured visitor-value claim is established. Source paths and commit IDs are provenance, not public reading URLs. Do not invent a public Rose history page or link to the private reference.",
  ROSE_PURPOSE,
  "Current repository capabilities:\n" + ROSE_CAPABILITIES.map(x => `- ${x}`).join("\n"),
  "Limits:\n" + ROSE_LIMITS.map(x => `- ${x}`).join("\n"),
  ...ROSE_HISTORY.map(e => `## ${e.id} (${e.date ?? "date unverified"}, ${e.claim})\n${e.text}\nProvenance: ${[...e.provenance.commits, ...e.provenance.plans, ...e.provenance.files].join("; ")}${e.notThis ? `\nUnsupported wording: ${e.notThis}` : ""}`),
].join("\n\n");
if (reference.length > 16000) throw new Error("History exceeds the 16,000-character budget");
const outputs = {
  "supabase/functions/_shared/rose-knowledge.generated.ts": `// Generated by scripts/generate-rose-history.ts. Private runtime artifact, do not edit.\nexport const ROSE_KNOWLEDGE_VERSION = 1;\nexport const ROSE_KNOWLEDGE_HASH = ${JSON.stringify(hash)};\nexport const ROSE_HISTORY_REFERENCE = ${JSON.stringify(reference)};\nexport const ROSE_PERSONA_RULES = ${JSON.stringify(ROSE_SELF_PERSONA.join("\n"))};\n`,
  "docs/rose-history.generated.md": `<!-- Generated. Private review artifact, excluded from public content. v1 sha256:${hash} -->\n\n${reference}\n`,
};
for (const [path, content] of Object.entries(outputs)) {
  if (process.argv.includes("--check")) {
    if (!existsSync(path) || readFileSync(path, "utf8") !== content) throw new Error(`Rose knowledge drift: ${path}`);
  } else writeFileSync(path, content);
}
console.log(`Rose knowledge v1 verified, ${reference.length} reference characters`);