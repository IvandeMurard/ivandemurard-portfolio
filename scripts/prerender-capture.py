#!/usr/bin/env python3
"""Capture the rendered body of each content route from a built dist/.

Serves dist/ locally (with SPA-style fallback so client routes resolve),
opens each route in headless Chromium with the site default theme and
reduced motion forced on, waits for the page to settle, then writes the
inner HTML of #root to prerendered/<slug>.html.

The files it writes are committed to the repo. scripts/apply-prerender.ts
injects them into the built HTML at postbuild time, so the head tags stay
generated by scripts/generate-seo-snapshots.ts and never go stale.

Usage:  python3 scripts/prerender-capture.py
"""

import asyncio
import json
import os
import re
import subprocess
import sys
import threading
from functools import partial
from http.server import SimpleHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIST = ROOT / "dist"
OUT = ROOT / "prerendered"
PORT = 4183
SETTLE_MS = 1800


def routes():
    """Read the route paths out of scripts/seo-routes.ts (single source of truth)."""
    src = (ROOT / "scripts" / "seo-routes.ts").read_text(encoding="utf8")
    body = src.split("export const SEO_ROUTES", 1)[1]
    return re.findall(r'^\s*path:\s*"([^"]+)"', body, re.M)


def slug_for(path):
    return "index" if path == "/" else path.strip("/").replace("/", "__")


class Handler(SimpleHTTPRequestHandler):
    def log_message(self, *args):
        pass

    def send_head(self):
        p = self.translate_path(self.path)
        if not os.path.exists(p) and "." not in os.path.basename(p):
            self.path = "/index.html"
        return super().send_head()


def serve():
    handler = partial(Handler, directory=str(DIST))
    httpd = ThreadingHTTPServer(("127.0.0.1", PORT), handler)
    threading.Thread(target=httpd.serve_forever, daemon=True).start()
    return httpd


async def capture():
    from playwright.async_api import async_playwright

    paths = routes()
    OUT.mkdir(exist_ok=True)
    written, failed = 0, []

    async with async_playwright() as p:
        browser = await p.chromium.launch(headless=True)
        context = await browser.new_context(
            viewport={"width": 1280, "height": 1800},
            reduced_motion="reduce",
            color_scheme="light",
        )
        page = await context.new_page()
        for path in paths:
            url = f"http://127.0.0.1:{PORT}{path}"
            try:
                await page.goto(url, wait_until="networkidle", timeout=45000)
                # Nudge every lazy-revealed section into its final state.
                await page.evaluate(
                    "async () => {"
                    "  const step = window.innerHeight;"
                    "  for (let y = 0; y < document.body.scrollHeight; y += step) {"
                    "    window.scrollTo(0, y);"
                    "    await new Promise(r => setTimeout(r, 120));"
                    "  }"
                    "  window.scrollTo(0, 0);"
                    "  document.querySelectorAll('[data-reveal]').forEach(el => el.setAttribute('data-revealed','true'));"
                    "}"
                )
                await page.wait_for_timeout(SETTLE_MS)
                html = await page.evaluate(
                    "() => { const r = document.getElementById('root'); return r ? r.innerHTML : ''; }"
                )
                if not html or len(html) < 2000:
                    raise RuntimeError(f"body too small ({len(html)} bytes)")
                (OUT / f"{slug_for(path)}.html").write_text(html, encoding="utf8")
                print(f"  captured {path} ({len(html)} bytes)")
                written += 1
            except Exception as exc:  # noqa: BLE001
                print(f"  FAILED {path}: {exc}")
                failed.append(path)
        await browser.close()

    print(f"[prerender] captured {written} route(s), {len(failed)} failed")
    return 1 if failed else 0


def main():
    if not (DIST / "index.html").exists():
        print("[prerender] dist/ missing, run the build first.")
        return 1
    httpd = serve()
    try:
        return asyncio.run(capture())
    finally:
        httpd.shutdown()


if __name__ == "__main__":
    sys.exit(main())
