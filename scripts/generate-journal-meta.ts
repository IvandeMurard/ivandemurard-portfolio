// Prebuild: writes src/content/journalMeta.generated.ts, the index data of every Field Note (title, decision, hook,
// dates, read times, revision dates) and the knowledge map, so the homepage and /journal never load a note body.
// Run with bun (tsconfig path aliases). Rewrites the file only when its content changed. `--check` exits 1 on drift.

import { readFileSync } from "fs";
import { resolve } from "path";
import { JOURNAL_ENTRIES, JOURNAL_KNOWLEDGE_QUESTIONS } from "@/content/journal";
import { writeIfChanged } from "./content-date";

export const renderJournalMeta = (): string => {
  const meta = JOURNAL_ENTRIES.map((e) => ({
    slug: e.slug,
    title: e.title,
    decision: e.decision,
    hook: e.hook,
    date: e.date,
    readingMinutes: e.readingMinutes,
    readingMinutesFull: e.readingMinutesFull,
    updates: (e.updates ?? []).map((u) => ({ date: u.date })),
  }));
  return [
    "// Generated by scripts/generate-journal-meta.ts from src/content/journal.ts. Do not edit.",
    "// Index data of each Field Note. No body text.",
    "",
    "export type JournalMeta = { slug: string; title: string; decision?: string; hook?: string; date: string; readingMinutes?: number; readingMinutesFull?: number; updates?: { date: string }[] };",
    "export type KnowledgeQuestion = { number: string; label: string; question: string; description: string; slug: string; cases: { label: string; to: string }[] };",
    "",
    `export const JOURNAL_META: JournalMeta[] = ${JSON.stringify(meta, null, 2)};`,
    "",
    `export const KNOWLEDGE_QUESTIONS: KnowledgeQuestion[] = ${JSON.stringify(JOURNAL_KNOWLEDGE_QUESTIONS, null, 2)};`,
    "",
  ].join("\n");
};

if (process.argv[1] && /generate-journal-meta\.ts$/.test(process.argv[1])) {
  const path = resolve("src/content/journalMeta.generated.ts");
  const out = renderJournalMeta();
  if (process.argv.includes("--check")) {
    const current = (() => { try { return readFileSync(path, "utf8"); } catch { return ""; } })();
    if (current !== out) { console.error("[journal-meta] stale: run bun scripts/generate-journal-meta.ts"); process.exit(1); }
    console.log("[journal-meta] up to date");
  } else {
    const changed = writeIfChanged(path, out);
    console.log(`[journal-meta] ${changed ? "wrote" : "unchanged:"} src/content/journalMeta.generated.ts, ${Buffer.byteLength(out)} bytes`);
  }
}
