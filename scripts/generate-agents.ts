// Generates the /agents content from real sources, never hand-written:
// - src/content/agents.generated.ts : build date + the Sonor excerpt exactly as
//   get_case_study returns it (status line + first lines of public/sonor.md)
// - public/agents.md : the Markdown mirror of /agents
// Runs in prebuild, before the sitemap and llms-full.
import { readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { AGENTS_DOC, renderAgentsMarkdown } from "../src/content/agents";
import { statusLine } from "../src/content/statuses";

const date = new Date().toISOString().slice(0, 10);
const sonor = readFileSync(resolve("public/sonor.md"), "utf8").replace(/\r\n/g, "\n");
const response = `${statusLine("sonor")}\n\n${sonor}`;
const excerpt = response.split("\n").slice(0, 5).join("\n");
if (!excerpt.includes(AGENTS_DOC.highlight)) {
  throw new Error(`[agents] Sonor excerpt no longer contains "${AGENTS_DOC.highlight}"`);
}

writeFileSync(
  resolve("src/content/agents.generated.ts"),
  `// AUTO-GENERATED by scripts/generate-agents.ts. Do not edit.\nexport const AGENTS_BUILD_DATE = ${JSON.stringify(date)};\nexport const SONOR_EXCERPT = ${JSON.stringify(excerpt)};\n`,
);
writeFileSync(resolve("public/agents.md"), renderAgentsMarkdown(date, excerpt));
console.log(`[agents] wrote agents.md and excerpt (${date})`);
